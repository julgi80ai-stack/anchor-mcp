-- v11 → v12: 실패한 요청의 **귀속**과 **종류** (D-283).
--
-- 두 열을 한 마이그레이션으로 낸다. 같은 결함의 두 얼굴이고, 하나만 넣으면
-- 남은 하나가 다음 라운드의 스키마 변경이 되기 때문이다(CLAUDE.md: 스키마
-- 변경은 한 라운드에 하나로 묶는다).
--
-- **url** — 첫 페치가 실패하면 `documents` 행이 없어 `document_id`가 `-`가
-- 된다. 실사용 저장소의 오류 148건 중 **141건**이 그 상태였다. 무엇을 못
-- 가져왔는지 남지 않으므로 재시도도, 재고 조사도, "그 미스가 중요했는지"의
-- 판단도 불가능하다. 손해의 크기를 모른다는 것 자체가 손해다.
--
-- **error_kind** — 상태코드는 "무엇이 실패했는가"를 말하지 않는다. 실측 두
-- 가지가 그것을 보여준다. (1) `error + 203` 2건이 "203을 거부했다"로 읽혔지만
-- 203은 성공 경로이고(`REPRESENTATION_STATUSES = {200, 203}`), 본문 5,565B·
-- 6,906B를 다 받은 뒤의 추출 실패였다 — 200의 추출 실패 2건과 같은 사건이
-- 상태코드 때문에 다른 병으로 보였다. (2) 상태코드 NULL 41건에 robots 거부와
-- 연결 실패와 타임아웃이 한 칸에 접혀 있다. 종류는 **예외 계층이 이미 알고
-- 있는 사실**이므로 새로 판정하지 않고 그대로 적는다.
--
-- 기존 행은 둘 다 NULL이다 — 지나간 요청의 URL도 예외 종류도 되짚을 방법이
-- 없다. `documents.url`로 채워 넣지 않는 이유는 그것이 "이 요청이 향한
-- URL"이라는 **알지 못하는 사실**을 단정하는 것이기 때문이다. 리다이렉트·
-- 별칭·병합을 지난 뒤의 문서 URL은 그때 요청한 URL과 다를 수 있다.
-- (v7 occurrences·v8 coverage·v11 last_observed_raw_hash와 같은 판단.)
ALTER TABLE fetch_log ADD COLUMN url TEXT;
ALTER TABLE fetch_log ADD COLUMN error_kind TEXT;
