-- v10 → v11: 이 판본을 **마지막으로 관측했을 때의 원본 바이트** (D-274).
--
-- `raw_changed`는 "원본 바이트는 달라졌는데 추출 본문은 같다"를 알리는
-- 신호다(D-232) — 추출 사각지대를 가리키는 유일한 저비용 단서다. 그런데
-- 비교 상대가 `versions.raw_hash`, 즉 **그 판본을 만든 바이트**였다. 그 값은
-- Memento의 좌표라 갱신되지 않으므로, 광고 nonce 하나로 바이트가 한 번
-- 달라지면 그 뒤로는 **바이트가 한 글자도 변하지 않은 재확인에서도** 매번
-- 참이 된다(실측: 3·4·5회차 모두 참). 사각지대 경고가 영구히 반복되면
-- 신호가 노이즈에 죽는다.
--
-- `raw_hash`를 덮어쓰지 않는 이유: 그것은 이 본문이 **어느 바이트에서
-- 나왔는가**라는 출처 사실이고, `renormalized` 판정(같은 바이트인데 파이프
-- 라인만 달라짐)이 읽는 값이다. 덮으면 우리가 정규화한 적 없는 바이트와
-- 비교하게 된다. `captured_at`(그때)과 `last_observed_at`(지금)을 가른 v6과
-- 같은 판단이며, 판본 행은 "그때"를 말하고 응답은 "지금"을 말한다는 규칙
-- (SPEC §7.5)의 세 번째 적용이다.
--
-- 기존 행은 NULL이다 — 마지막 관측의 바이트를 되짚을 방법이 없다. 그때는
-- `raw_hash`로 물러서므로 업그레이드 직후 관측 한 번이 예전 비교를 반복할
-- 수 있고, 그 뒤로는 스스로 바로잡힌다. `raw_hash`로 채워 넣지 않는 이유는
-- 그것이 "마지막으로 관측한 바이트"라는 **알지 못하는 사실**을 단정하는
-- 것이기 때문이다 (v7 occurrences·v8 coverage와 같은 판단).
ALTER TABLE versions ADD COLUMN last_observed_raw_hash TEXT;
